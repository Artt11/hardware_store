"""Phase 1, Task 6: the Alembic baseline matches the models and round-trips."""

import asyncio

import pytest
from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession

from alembic import command

REQUIRED_EXTENSIONS = {"pg_trgm", "pgcrypto", "citext", "uuid-ossp"}
EXPECTED_TABLES = {
    "users",
    "categories",
    "products",
    "inventory",
    "carts",
    "cart_items",
    "wishlist_items",
    "orders",
    "order_items",
    "user_sessions",
}


async def test_upgrade_enables_required_extensions(db_session: AsyncSession) -> None:
    rows = await db_session.scalars(text("SELECT extname FROM pg_extension"))
    assert REQUIRED_EXTENSIONS <= set(rows)


async def test_upgrade_creates_all_tables(db_session: AsyncSession) -> None:
    rows = await db_session.scalars(text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'"))
    assert EXPECTED_TABLES <= set(rows)


async def test_search_indexes_use_trigram_gin(db_session: AsyncSession) -> None:
    rows = (
        await db_session.execute(
            text("SELECT indexname, indexdef FROM pg_indexes WHERE tablename = 'products'")
        )
    ).all()
    defs = dict(rows)
    assert "gin_trgm_ops" in defs["ix_products_name_trgm"]
    assert "gin_trgm_ops" in defs["ix_products_sku_trgm"]
    assert "jsonb_path_ops" in defs["ix_products_specifications"]


async def test_models_and_migration_have_no_drift(alembic_cfg: Config) -> None:
    # Raises AutoGenerateDiffsDetected listing every difference.
    await asyncio.to_thread(command.check, alembic_cfg)


async def test_downgrade_then_upgrade_round_trips(alembic_cfg: Config, engine: AsyncEngine) -> None:
    await asyncio.to_thread(command.downgrade, alembic_cfg, "base")
    async with engine.connect() as conn:
        tables = set(await conn.scalars(text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")))
    assert tables <= {"alembic_version"}

    await asyncio.to_thread(command.upgrade, alembic_cfg, "head")
    async with engine.connect() as conn:
        tables = set(await conn.scalars(text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")))
    assert EXPECTED_TABLES <= tables


async def test_order_numbers_come_from_a_sequence(db_session: AsyncSession) -> None:
    first, second = (
        await db_session.scalar(text("SELECT 'SURO-' || lpad(nextval('order_number_seq')::text, 7, '0')")),
        await db_session.scalar(text("SELECT 'SURO-' || lpad(nextval('order_number_seq')::text, 7, '0')")),
    )
    assert first != second
    assert first is not None and first.startswith("SURO-") and len(first) == 12


@pytest.mark.parametrize("tax_id", ["1234567", "12A45678", "1234567 "])
async def test_company_tax_id_must_be_eight_digits(db_session: AsyncSession, tax_id: str) -> None:
    with pytest.raises(IntegrityError, match="ck_users_tax_id_hvhh"):
        await db_session.execute(
            text(
                "INSERT INTO users (email, password_hash, account_type, role, company_name, tax_id, "
                "contact_person) VALUES ('b2b@example.com', 'x', 'company', 'customer', 'Co', "
                ":tax_id, 'Anna')"
            ),
            {"tax_id": tax_id},
        )


async def test_emails_are_case_insensitive_unique(db_session: AsyncSession) -> None:
    insert = text(
        "INSERT INTO users (email, password_hash, first_name, last_name) VALUES (:e, 'x', 'A', 'B')"
    )
    await db_session.execute(insert, {"e": "Anna@Example.com"})
    with pytest.raises(IntegrityError, match="uq_users_email"):
        await db_session.execute(insert, {"e": "anna@example.com"})


async def test_inventory_cannot_go_negative(db_session: AsyncSession) -> None:
    category_id = await db_session.scalar(
        text("INSERT INTO categories (slug, name) VALUES ('t', 'T') RETURNING id")
    )
    product_id = await db_session.scalar(
        text(
            "INSERT INTO products (category_id, sku, slug, name, retail_price) "
            "VALUES (:c, 'T1', 't1', 'Test', 100) RETURNING id"
        ),
        {"c": category_id},
    )
    with pytest.raises(IntegrityError, match="ck_inventory_on_hand_non_negative"):
        await db_session.execute(
            text("INSERT INTO inventory (product_id, quantity_on_hand) VALUES (:p, -1)"), {"p": product_id}
        )


async def test_armenian_text_is_searchable_case_insensitively(db_session: AsyncSession) -> None:
    """Fails under a C-locale database: Armenian letters would yield no trigrams."""
    trigrams = await db_session.scalar(text("SELECT cardinality(show_trgm('Մեխ'))"))
    assert trigrams and trigrams > 0

    category_id = await db_session.scalar(
        text("INSERT INTO categories (slug, name) VALUES ('fasteners', 'Ամրակման միջոցներ') RETURNING id")
    )
    await db_session.execute(
        text(
            "INSERT INTO products (category_id, sku, slug, name, retail_price) "
            "VALUES (:c, '00001', 'p-00001', 'Մեխ 100մմ', 500)"
        ),
        {"c": category_id},
    )
    found = await db_session.scalar(text("SELECT count(*) FROM products WHERE name ILIKE '%մեխ%'"))
    assert found == 1
